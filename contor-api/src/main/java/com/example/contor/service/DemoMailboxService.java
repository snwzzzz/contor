/**
 * Stores the fictional business mailbox (generated by {@code scripts/business-dataset/build.mjs}) as a user's mail, so
 * the app can be tried and demonstrated on realistic business mail: one {@link MailProvider#DEMO} account per mailbox of
 * the dataset (never synced), the business collections and relation types ({@link BusinessCollections}), and every
 * message — inbox mail as NEW for the AI processing, sent mail SKIPPED like synced sent mail. Runs once per user.
 */
@Slf4j
@RequiredArgsConstructor
@Service
public class DemoMailboxService {

    /** Who the demo mailbox's owner is, for the AI settings (the evaluation of the dataset uses the same text). */
    public static final String OWNER_PROFILE = "I am Alex Morgan, Head of Operations at Nordhafen Industriebedarf GmbH in Hamburg, a wholesaler "
            + "of industrial tools, fasteners, bearings and spare parts. Customers (machine builders and workshops across Europe) "
            + "order from us: their orders are sales orders for us, even when they call them their PO; our order confirmations "
            + "have numbers like SO-26-0151. We buy from suppliers in Poland, Spain, Italy, Czechia, Slovenia, Turkey and Germany "
            + "with our own purchase orders (PO-26-1083). Carriers and forwarders ship our goods to customers (outbound) and our "
            + "suppliers' goods to us (inbound). My colleagues (@nordhafen.example) run the warehouse, accounting and sales; "
            + "the managing director is Dr. Helga Sommerfeld.";

    private static final int SNIPPET_LENGTH = 200;
    private static final ObjectMapper MAPPER = JsonMapper.builder().disable(DeserializationFeature.FAIL_ON_UNKNOWN_PROPERTIES).build();

    private final MailAccountRepository mailAccountRepository;
    private final EmailMessageRepository emailMessageRepository;
    private final CollectionSchemaService collectionSchemaService;
    private final RelationTypeService relationTypeService;
    private final AiSettingsRepository aiSettingsRepository;
    private final Clock clock;

    /** The parts of a generated message file the import needs. */
    record DemoMessage(String id, String account, String folder, String conversationId, List<String> cc, Mail email) {

        record Mail(String mailbox, String fromName, String fromAddress, List<String> to, String subject, Instant receivedAt, String body) {
        }

        boolean sent() {
            return EmailMessage.FOLDER_SENT.equals(folder);
        }
    }

    /**
     * @param mailbox      folder with the {@code m-*.json} message files
     * @param shiftToToday move all dates by whole weeks so the newest message is from the last seven days
     * @return the number of imported messages; 0 when the owner already has the demo mailbox
     */
    @Transactional
    public int importMailbox(AppUser owner, Path mailbox, boolean shiftToToday) {
        if (!Files.isDirectory(mailbox)) {
            throw new IllegalArgumentException("Demo mailbox folder not found: " + mailbox.toAbsolutePath());
        }
        if (mailAccountRepository.existsByOwner_IdAndProvider(owner.getId(), MailProvider.DEMO)) {
            return 0;
        }
        List<DemoMessage> messages = read(mailbox);
        if (messages.isEmpty()) {
            return 0;
        }
        Duration shift = shiftToToday ? shift(messages.getLast().email().receivedAt()) : Duration.ZERO;

        Map<String, MailAccount> accounts = new LinkedHashMap<>();
        for (DemoMessage message : messages) {
            accounts.computeIfAbsent(message.account(), key -> mailAccountRepository.save(MailAccount.builder().owner(owner)
                    .provider(MailProvider.DEMO).emailAddress(new Email(message.email().mailbox()))
                    .displayName("Nordhafen demo (" + key + ")").status(MailAccountStatus.ACTIVE).lastSyncedAt(clock.instant())
                    .photoCheckedAt(clock.instant()).contactsCheckedAt(clock.instant()).build()));
        }
        ensureSchema();
        describeOwner(owner);
        emailMessageRepository.saveAll(messages.stream().map(message -> toEmail(message, accounts.get(message.account()), shift)).toList());
        log.info("Demo mailbox: {} messages in {} accounts imported (dates shifted by {} days)", messages.size(), accounts.size(), shift.toDays());
        return messages.size();
    }

    /** Whole weeks from the newest message to now, so weekdays in the texts stay right. */
    private Duration shift(Instant newest) {
        long days = ChronoUnit.DAYS.between(newest.atZone(ZoneOffset.UTC).toLocalDate(), clock.instant().atZone(ZoneOffset.UTC).toLocalDate());
        return Duration.ofDays(Math.max(0, days / 7) * 7);
    }

    private static List<DemoMessage> read(Path mailbox) {
        try (Stream<Path> files = Files.list(mailbox)) {
            return files.filter(file -> file.getFileName().toString().endsWith(".json")).map(DemoMailboxService::parse)
                    .sorted(Comparator.comparing((DemoMessage message) -> message.email().receivedAt()).thenComparing(DemoMessage::id))
                    .toList();
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
    }

    private static DemoMessage parse(Path file) {
        try {
            return MAPPER.readValue(Files.readString(file), DemoMessage.class);
        } catch (IOException | RuntimeException e) {
            throw new IllegalArgumentException("Cannot read demo message " + file.getFileName() + ": " + e.getMessage(), e);
        }
    }

    private static EmailMessage toEmail(DemoMessage message, MailAccount account, Duration shift) {
        DemoMessage.Mail mail = message.email();
        String body = mail.body() != null ? mail.body() : "";
        String snippet = body.replaceAll("\\s+", " ").strip();
        return EmailMessage.builder().account(account)
                .providerMessageId("demo-" + message.id()).internetMessageId("<" + message.id() + "@demo.nordhafen.example>")
                .conversationId(message.conversationId()).folder(message.sent() ? EmailMessage.FOLDER_SENT : "inbox")
                .fromName(mail.fromName()).fromAddress(mail.fromAddress())
                .toRecipients(recipients(mail.to())).ccRecipients(recipients(message.cc()))
                .subject(mail.subject()).snippet(snippet.substring(0, Math.min(SNIPPET_LENGTH, snippet.length()))).bodyText(body)
                .receivedAt(mail.receivedAt().plus(shift)).read(message.sent())
                .processingState(message.sent() ? ProcessingState.SKIPPED : ProcessingState.NEW)
                .build();
    }

    private static List<EmailRecipient> recipients(List<String> addresses) {
        return new ArrayList<>(addresses == null ? List.of() : addresses.stream().map(address -> new EmailRecipient(null, address)).toList());
    }

    /** Tells the AI whose mailbox this is, unless the user already wrote their own profile. */
    private void describeOwner(AppUser owner) {
        AiSettings settings = aiSettingsRepository.findByUser_Id(owner.getId()).orElseGet(() -> AiSettings.defaults(owner));
        if (settings.getOwnerProfile() == null || settings.getOwnerProfile().isBlank()) {
            settings.setOwnerProfile(OWNER_PROFILE);
            aiSettingsRepository.save(settings);
        }
    }

    /** The business collections and relation types, unless they exist already. */
    private void ensureSchema() {
        Map<String, Long> ids = new LinkedHashMap<>();
        collectionSchemaService.findAll().forEach(collection -> ids.put(collection.getSlug(), collection.getId()));
        BusinessCollections.commands().stream().filter(command -> !ids.containsKey(command.getSlug())).forEach(command -> {
            CollectionDto created = collectionSchemaService.createCollection(command);
            ids.put(created.getSlug(), created.getId());
        });
        Set<String> types = relationTypeService.findAll().stream().map(RelationTypeDto::getSlug).collect(Collectors.toSet());
        BusinessCollections.relationTypes().stream().filter(spec -> !types.contains(spec.slug())).forEach(spec ->
                relationTypeService.createRelationType(new NewRelationTypeCommand(spec.slug(), spec.name()).inverseName(spec.inverseName())
                        .fromCollectionId(ids.get(spec.from())).toCollectionId(ids.get(spec.to())).directed(true)));
    }
}
