-- External APIs ("Apps", ADR 0012): HTTP APIs a user connects so the assistant can learn from them. An app is private
-- to its owner. contor only calls the endpoints the user confirmed (read-only), on the app's own interval, and keeps
-- the last answers, the items found in them and which record each item became.
create sequence external_api_seq start with 1 increment by 50;
create sequence external_api_endpoint_seq start with 1 increment by 50;
create sequence external_api_mapping_seq start with 1 increment by 50;

create table "external_api" (
    id bigint not null,
    owner_id bigint not null,
    name text not null,
    slug text not null,
    description text,
    base_url text not null,
    docs_url text,
    auth_kind text not null default 'NONE',
    auth_config jsonb not null default '{}'::jsonb,
    secret_enc text,
    headers jsonb not null default '[]'::jsonb,
    poll_interval_minutes int not null default 360,
    enabled boolean not null default true,
    ai_analysis boolean not null default true,
    status text not null default 'ACTIVE',
    last_called_at timestamptz,
    next_call_at timestamptz,
    failure_count int not null default 0,
    last_error text,
    daily_request_limit int not null default 200,
    created_at timestamptz not null,
    last_modified timestamptz,
    constraint pk_external_api primary key (id),
    constraint fk_external_api_app_user foreign key (owner_id) references "app_user" (id) on delete cascade,
    constraint uq_external_api_owner_slug unique (owner_id, slug),
    constraint ck_external_api_auth_kind check (auth_kind in ('NONE', 'API_KEY_HEADER', 'API_KEY_QUERY', 'BEARER', 'BASIC',
        'OAUTH2_CLIENT_CREDENTIALS')),
    constraint ck_external_api_status check (status in ('ACTIVE', 'FAILING', 'PAUSED', 'NEEDS_SETUP')),
    constraint ck_external_api_poll_interval check (poll_interval_minutes between 15 and 10080),
    constraint ck_external_api_daily_request_limit check (daily_request_limit between 1 and 10000),
    constraint ck_external_api_failure_count check (failure_count >= 0)
);
create index ix_external_api_owner on "external_api" (owner_id);
create index ix_external_api_next_call on "external_api" (next_call_at) where enabled;
comment on table "external_api" is 'External APIs a user connected; secret_enc holds the encrypted credentials and secret header values (JSON), headers the plain ones';

create table "external_api_endpoint" (
    id bigint not null,
    api_id bigint not null,
    name text not null,
    method text not null default 'GET',
    path text not null,
    query jsonb not null default '{}'::jsonb,
    body jsonb,
    items_path text,
    item_key_path text,
    description text,
    source text not null default 'USER',
    enabled boolean not null default true,
    created_at timestamptz not null,
    last_modified timestamptz,
    constraint pk_external_api_endpoint primary key (id),
    constraint fk_external_api_endpoint_external_api foreign key (api_id) references "external_api" (id) on delete cascade,
    constraint uq_external_api_endpoint_api_name unique (api_id, name),
    constraint ck_external_api_endpoint_method check (method in ('GET', 'POST')),
    constraint ck_external_api_endpoint_source check (source in ('USER', 'DOCS', 'MODEL')),
    constraint ck_external_api_endpoint_body check (body is null or method = 'POST')
);
create index ix_external_api_endpoint_api on "external_api_endpoint" (api_id);
comment on table "external_api_endpoint" is 'Confirmed endpoints of an external API: path below the base URL, fixed query and body; items_path/item_key_path find the items in the answer';

create table "external_api_mapping" (
    id bigint not null,
    endpoint_id bigint not null,
    collection_id bigint not null,
    title_path text,
    field_map jsonb not null default '[]'::jsonb,
    state text not null default 'PROPOSED',
    created_at timestamptz not null,
    last_modified timestamptz,
    constraint pk_external_api_mapping primary key (id),
    constraint fk_external_api_mapping_external_api_endpoint foreign key (endpoint_id) references "external_api_endpoint" (id) on delete cascade,
    constraint fk_external_api_mapping_collection foreign key (collection_id) references "collection" (id),
    constraint uq_external_api_mapping_endpoint_collection unique (endpoint_id, collection_id),
    constraint ck_external_api_mapping_state check (state in ('PROPOSED', 'ACTIVE', 'OFF'))
);
create index ix_external_api_mapping_collection on "external_api_mapping" (collection_id);
comment on table "external_api_mapping" is 'How the items of an endpoint become records of a collection (field slug <- JSON path); proposed by the model, approved by the user';

create table "external_api_call" (
    id bigint generated by default as identity,
    endpoint_id bigint not null,
    started_at timestamptz not null,
    duration_ms int not null,
    http_status int,
    outcome text not null,
    error text,
    items_new int not null default 0,
    items_changed int not null default 0,
    items_gone int not null default 0,
    constraint pk_external_api_call primary key (id),
    constraint fk_external_api_call_external_api_endpoint foreign key (endpoint_id) references "external_api_endpoint" (id) on delete cascade,
    constraint ck_external_api_call_outcome check (outcome in ('OK', 'UNCHANGED', 'FAILED'))
);
create index ix_external_api_call_endpoint on "external_api_call" (endpoint_id, started_at desc);
create index ix_external_api_call_started_at on "external_api_call" (started_at);
comment on table "external_api_call" is 'Call history of the external API endpoints (pruned after 30 days); error is masked, never the URL or a credential';

create table "external_api_snapshot" (
    id bigint generated by default as identity,
    endpoint_id bigint not null,
    fetched_at timestamptz not null,
    content_hash text not null,
    content_type text,
    body text not null,
    truncated boolean not null default false,
    constraint pk_external_api_snapshot primary key (id),
    constraint fk_external_api_snapshot_external_api_endpoint foreign key (endpoint_id) references "external_api_endpoint" (id) on delete cascade
);
create index ix_external_api_snapshot_endpoint on "external_api_snapshot" (endpoint_id, fetched_at desc);
comment on table "external_api_snapshot" is 'The last answers of an endpoint as received (no request headers); an unchanged content_hash means nothing to do';

create table "external_api_item" (
    id bigint generated by default as identity,
    endpoint_id bigint not null,
    item_key text not null,
    item_hash text not null,
    data jsonb not null,
    first_seen_at timestamptz not null,
    last_seen_at timestamptz not null,
    gone_at timestamptz,
    collection_id bigint,
    record_id bigint,
    constraint pk_external_api_item primary key (id),
    constraint fk_external_api_item_external_api_endpoint foreign key (endpoint_id) references "external_api_endpoint" (id) on delete cascade,
    constraint fk_external_api_item_collection foreign key (collection_id) references "collection" (id),
    constraint uq_external_api_item_endpoint_key unique (endpoint_id, item_key),
    constraint ck_external_api_item_record check ((collection_id is null) = (record_id is null))
);
create index ix_external_api_item_record on "external_api_item" (collection_id, record_id);
comment on table "external_api_item" is 'Items found in an endpoint''s answers by key: last data and hash, when seen or gone, and the record (collection_id, record_id) it became';
