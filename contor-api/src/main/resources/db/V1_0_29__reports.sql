-- AI reports about one record and the connected records the user picked: an executive summary, key findings, timeline,
-- open questions and next steps, each sentence fact-checked and cited down to a record field or an email paragraph.
-- A follow-up question is a report of its own with parent_report_id set. Reports are snapshots: citations keep the
-- quoted text and the field value they were made from.
create sequence report_seq start with 1 increment by 50;

create table "report" (
    id bigint not null,
    collection_id bigint not null,
    record_id bigint not null,
    parent_report_id bigint,
    prompt text,
    title text,
    scope jsonb not null,
    status text not null default 'QUEUED',
    failure_reason text,
    model text,
    prompt_version text,
    claims_total int not null default 0,
    claims_verified int not null default 0,
    claims_removed int not null default 0,
    generated_at timestamptz,
    created_by_user_id bigint,
    created_at timestamptz not null,
    last_modified timestamptz,
    constraint pk_report primary key (id),
    constraint fk_report_collection foreign key (collection_id) references "collection" (id),
    constraint fk_report_parent_report foreign key (parent_report_id) references "report" (id) on delete cascade,
    constraint fk_report_app_user foreign key (created_by_user_id) references "app_user" (id) on delete set null,
    constraint ck_report_status check (status in ('QUEUED', 'COLLECTING', 'DRAFTING', 'FACT_CHECKING', 'READY', 'FAILED')),
    constraint ck_report_claim_counts check (claims_total >= 0 and claims_verified >= 0 and claims_removed >= 0)
);
-- record_id points into the generated table of the collection, so it has no FK.
create index ix_report_record on "report" (collection_id, record_id, created_at desc);
create index ix_report_parent_report_id on "report" (parent_report_id);
create index ix_report_created_by_user_id on "report" (created_by_user_id);
comment on table "report" is 'AI reports about a record (anchor collection_id, record_id) and its picked connections; follow-ups have parent_report_id';

create table "report_section" (
    id bigint generated by default as identity,
    report_id bigint not null,
    position int not null,
    kind text not null,
    title text not null,
    constraint pk_report_section primary key (id),
    constraint fk_report_section_report foreign key (report_id) references "report" (id) on delete cascade,
    constraint uq_report_section_report_position unique (report_id, position),
    constraint ck_report_section_kind check (kind in ('SUMMARY', 'FINDINGS', 'TIMELINE', 'OPEN_QUESTIONS', 'NEXT_STEPS', 'CUSTOM'))
);
comment on table "report_section" is 'Sections of a report in reading order';

create table "report_finding" (
    id bigint generated by default as identity,
    section_id bigint not null,
    position int not null,
    title text not null,
    severity text not null,
    event_date timestamptz,
    constraint pk_report_finding primary key (id),
    constraint fk_report_finding_report_section foreign key (section_id) references "report_section" (id) on delete cascade,
    constraint ck_report_finding_severity check (severity in ('POSITIVE', 'NEUTRAL', 'PROBLEM', 'RISK', 'CONFLICT'))
);
create index ix_report_finding_section_id on "report_finding" (section_id);
comment on table "report_finding" is 'Key findings and timeline entries of a section; their sentences are report_claim rows';

create table "report_claim" (
    id bigint generated by default as identity,
    section_id bigint not null,
    finding_id bigint,
    position int not null,
    text text not null,
    verification text not null,
    verifier_note text,
    constraint pk_report_claim primary key (id),
    constraint fk_report_claim_report_section foreign key (section_id) references "report_section" (id) on delete cascade,
    constraint fk_report_claim_report_finding foreign key (finding_id) references "report_finding" (id) on delete cascade,
    constraint ck_report_claim_verification check (verification in ('SUPPORTED', 'PARTIAL', 'REPAIRED', 'REMOVED', 'CONFLICT'))
);
create index ix_report_claim_section_id on "report_claim" (section_id);
create index ix_report_claim_finding_id on "report_claim" (finding_id);
comment on table "report_claim" is 'One sentence of a report with its fact-check result; REMOVED sentences are kept for the fact-check details';

-- A citation points at a record, one of its fields, an email paragraph or a relation. record_id and relation_id have
-- no FK (generated table / relations may be deleted); the snapshot columns keep what was cited.
create table "report_citation" (
    id bigint generated by default as identity,
    claim_id bigint not null,
    marker int not null,
    type text not null,
    collection_id bigint,
    record_id bigint,
    field_slug text,
    email_id bigint,
    paragraph_index int,
    paragraph_hash text,
    segmenter_version int,
    quote text,
    relation_id bigint,
    value_snapshot jsonb,
    is_supporting_quote boolean not null default false,
    constraint pk_report_citation primary key (id),
    constraint fk_report_citation_report_claim foreign key (claim_id) references "report_claim" (id) on delete cascade,
    constraint fk_report_citation_collection foreign key (collection_id) references "collection" (id),
    constraint fk_report_citation_email_message foreign key (email_id) references "email_message" (id) on delete set null,
    constraint ck_report_citation_type check (type in ('RECORD', 'FIELD', 'EMAIL_PARAGRAPH', 'RELATION')),
    -- email_id is not required: a deleted email leaves the citation with its quote (shown as deleted).
    constraint ck_report_citation_target check (
        (type = 'RECORD' and collection_id is not null and record_id is not null)
        or (type = 'FIELD' and collection_id is not null and record_id is not null and field_slug is not null)
        or (type = 'EMAIL_PARAGRAPH' and paragraph_index is not null and paragraph_hash is not null
            and segmenter_version is not null and quote is not null)
        or (type = 'RELATION' and relation_id is not null))
);
create index ix_report_citation_claim_id on "report_citation" (claim_id);
create index ix_report_citation_email_id on "report_citation" (email_id);
create index ix_report_citation_record on "report_citation" (collection_id, record_id);
comment on table "report_citation" is 'Sources of a report sentence: record, field (with value snapshot), email paragraph (with quote) or relation';
