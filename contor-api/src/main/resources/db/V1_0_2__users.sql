-- Accounts that can log in. The first one (OWNER) is created through the one-time setup endpoint.
create sequence app_user_seq start with 1 increment by 50;

create table "app_user" (
    id bigint not null,
    username text not null,
    email text not null,
    password_hash text not null,
    role text not null,
    totp_secret_enc text,
    totp_enabled boolean not null default false,
    failed_login_attempts int not null default 0,
    locked_until timestamptz,
    last_login_at timestamptz,
    created_at timestamptz not null,
    last_modified timestamptz,
    constraint pk_app_user primary key (id),
    constraint uq_app_user_username unique (username),
    constraint ck_app_user_role check (role in ('OWNER', 'USER'))
);

-- One-time TOTP recovery codes (hashed). Detail table of app_user.
create table "recovery_code" (
    id bigint generated by default as identity,
    user_id bigint not null,
    code_hash text not null,
    used_at timestamptz,
    constraint pk_recovery_code primary key (id),
    constraint fk_recovery_code_app_user foreign key (user_id) references "app_user" (id) on delete cascade
);
create index ix_recovery_code_user_id on "recovery_code" (user_id);
