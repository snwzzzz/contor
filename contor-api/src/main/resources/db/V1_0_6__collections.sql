-- Metadata of user/AI-defined collections. Each collection owns one generated table (table_name, e.g. c_deliveries)
-- that holds its records; that table is managed via jOOQ, never via Flyway or JPA.
create sequence collection_seq start with 1 increment by 50;

create table "collection" (
    id bigint not null,
    slug text not null,
    name text not null,
    description text,
    table_name text not null,
    icon text,
    is_system boolean not null default false,
    match_keys jsonb not null default '[]',
    display_config jsonb not null default '{}',
    schema_version int not null default 1,
    created_by text not null,
    archived_at timestamptz,
    created_at timestamptz not null,
    last_modified timestamptz,
    constraint pk_collection primary key (id),
    constraint uq_collection_slug unique (slug),
    constraint uq_collection_table_name unique (table_name),
    constraint ck_collection_created_by check (created_by in ('USER', 'AI'))
);

-- Field definitions of a collection; each maps to one or more columns of the generated table.
create sequence collection_field_seq start with 1 increment by 50;

create table "collection_field" (
    id bigint not null,
    collection_id bigint not null,
    slug text not null,
    name text not null,
    description text,
    type text not null,
    options jsonb not null default '{}',
    required boolean not null default false,
    unique_value boolean not null default false,
    position int not null,
    column_name text not null,
    archived_at timestamptz,
    created_at timestamptz not null,
    last_modified timestamptz,
    constraint pk_collection_field primary key (id),
    constraint fk_collection_field_collection foreign key (collection_id) references "collection" (id) on delete cascade,
    constraint uq_collection_field_collection_slug unique (collection_id, slug),
    constraint uq_collection_field_collection_column_name unique (collection_id, column_name),
    constraint ck_collection_field_type check (type in ('TEXT', 'LONG_TEXT', 'NUMBER', 'MONEY', 'DATE', 'DATETIME', 'BOOLEAN',
                                                       'ENUM', 'STATUS', 'URL', 'EMAIL', 'PHONE', 'RELATION', 'FILE'))
);
create index ix_collection_field_collection_id on "collection_field" (collection_id);

-- Append-only history of every generated DDL statement per collection.
create table "collection_schema_change" (
    id bigint generated by default as identity,
    collection_id bigint not null,
    from_version int not null,
    to_version int not null,
    change jsonb not null,
    ddl_executed text not null,
    executed_at timestamptz not null,
    executed_by bigint,
    constraint pk_collection_schema_change primary key (id),
    constraint fk_collection_schema_change_collection foreign key (collection_id) references "collection" (id),
    constraint fk_collection_schema_change_app_user foreign key (executed_by) references "app_user" (id) on delete set null
);
create index ix_collection_schema_change_collection_id on "collection_schema_change" (collection_id, to_version);
create index ix_collection_schema_change_executed_by on "collection_schema_change" (executed_by);

create trigger trg_collection_schema_change_append_only
    before update or delete on "collection_schema_change"
    for each row execute function forbid_update_delete();
