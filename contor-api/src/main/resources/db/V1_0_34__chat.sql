-- The AI chat: a user's conversations with the local model about everything in contor. Each turn is a USER message
-- and an ASSISTANT answer written in the background (state); an answer keeps its parsed Markdown blocks, the records
-- and emails it mentions (links) and its citations, like a report. Conversations are private to their user.
create sequence chat_conversation_seq start with 1 increment by 50;
create sequence chat_message_seq start with 1 increment by 50;

create table "chat_conversation" (
    id bigint not null,
    owner_id bigint not null,
    title text not null,
    focus jsonb not null default '[]'::jsonb,
    created_at timestamptz not null,
    last_modified timestamptz,
    constraint pk_chat_conversation primary key (id),
    constraint fk_chat_conversation_app_user foreign key (owner_id) references "app_user" (id) on delete cascade
);
create index ix_chat_conversation_owner on "chat_conversation" (owner_id, last_modified desc);
comment on table "chat_conversation" is 'AI chat conversations of a user; focus holds the records (collection_id, record_id) the next turn refers to';

create table "chat_message" (
    id bigint not null,
    conversation_id bigint not null,
    position int not null,
    role text not null,
    content text,
    state text not null default 'DONE',
    error text,
    blocks jsonb not null default '[]'::jsonb,
    mentions jsonb not null default '[]'::jsonb,
    plan jsonb,
    model text,
    prompt_version text,
    plan_ms int,
    answer_ms int,
    created_at timestamptz not null,
    last_modified timestamptz,
    constraint pk_chat_message primary key (id),
    constraint fk_chat_message_chat_conversation foreign key (conversation_id) references "chat_conversation" (id) on delete cascade,
    constraint uq_chat_message_conversation_position unique (conversation_id, position),
    constraint ck_chat_message_role check (role in ('USER', 'ASSISTANT')),
    constraint ck_chat_message_state check (state in ('PENDING', 'RETRIEVING', 'WRITING', 'DONE', 'FAILED'))
);
create index ix_chat_message_state on "chat_message" (state) where state in ('PENDING', 'RETRIEVING', 'WRITING');
comment on table "chat_message" is 'Questions and answers of a chat conversation in order (position); content is the question or the answer as plain text';

-- Same targets as report_citation. record_id and relation_id have no FK (generated table / relations may be deleted);
-- the snapshot columns keep what was cited.
create table "chat_citation" (
    id bigint generated by default as identity,
    message_id bigint not null,
    marker int not null,
    type text not null,
    collection_id bigint,
    record_id bigint,
    field_slug text,
    email_id bigint,
    paragraph_index int,
    paragraph_hash text,
    segmenter_version int,
    quote text,
    relation_id bigint,
    value_snapshot jsonb,
    constraint pk_chat_citation primary key (id),
    constraint fk_chat_citation_chat_message foreign key (message_id) references "chat_message" (id) on delete cascade,
    constraint fk_chat_citation_collection foreign key (collection_id) references "collection" (id),
    constraint fk_chat_citation_email_message foreign key (email_id) references "email_message" (id) on delete set null,
    constraint ck_chat_citation_type check (type in ('RECORD', 'FIELD', 'EMAIL_PARAGRAPH', 'RELATION')),
    constraint ck_chat_citation_target check (
        (type = 'RECORD' and collection_id is not null and record_id is not null)
        or (type = 'FIELD' and collection_id is not null and record_id is not null and field_slug is not null)
        or (type = 'EMAIL_PARAGRAPH' and paragraph_index is not null and paragraph_hash is not null
            and segmenter_version is not null and quote is not null)
        or (type = 'RELATION' and relation_id is not null))
);
create index ix_chat_citation_message_id on "chat_citation" (message_id);
create index ix_chat_citation_email_id on "chat_citation" (email_id);
create index ix_chat_citation_record on "chat_citation" (collection_id, record_id);
comment on table "chat_citation" is 'Sources of a chat answer: record, field (with value snapshot), email paragraph (with quote) or relation';
