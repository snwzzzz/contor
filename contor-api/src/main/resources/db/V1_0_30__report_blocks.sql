-- Reports are written as documents: a section holds blocks (paragraphs, bullet and numbered lists, quotes, tables)
-- whose sentences, list items and table cells are report_claim rows with their own citations.
create table "report_block" (
    id bigint generated by default as identity,
    section_id bigint not null,
    position int not null,
    kind text not null,
    columns jsonb,
    constraint pk_report_block primary key (id),
    constraint fk_report_block_report_section foreign key (section_id) references "report_section" (id) on delete cascade,
    constraint uq_report_block_section_position unique (section_id, position),
    constraint ck_report_block_kind check (kind in ('PARAGRAPH', 'BULLETS', 'NUMBERED', 'QUOTE', 'TABLE'))
);
comment on table "report_block" is 'Paragraphs, lists, quotes and tables of a report section in reading order; columns is the header of a table';

alter table "report_claim"
    add column block_id bigint,
    add column row_index int,
    add column column_index int,
    add constraint fk_report_claim_report_block foreign key (block_id) references "report_block" (id) on delete cascade,
    add constraint ck_report_claim_cell check ((row_index is null) = (column_index is null) and (row_index is null or block_id is not null));
create index ix_report_claim_block_id on "report_claim" (block_id);
comment on column "report_claim".block_id is 'The block of a sentence, list item or table cell (row_index, column_index)';
