-- Links a record (collection_id, record_id) to the emails it was created from, updated from or mentioned in.
-- record_id points into the generated table of the collection, so it has no FK.
create table "record_source" (
    id bigint generated by default as identity,
    collection_id bigint not null,
    record_id bigint not null,
    email_id bigint not null,
    role text not null,
    created_at timestamptz not null,
    constraint pk_record_source primary key (id),
    constraint fk_record_source_collection foreign key (collection_id) references "collection" (id),
    constraint fk_record_source_email_message foreign key (email_id) references "email_message" (id) on delete cascade,
    constraint uq_record_source_record_email_role unique (collection_id, record_id, email_id, role),
    constraint ck_record_source_role check (role in ('CREATED_FROM', 'UPDATED_FROM', 'MENTIONED_IN'))
);
create index ix_record_source_record on "record_source" (collection_id, record_id);
create index ix_record_source_email_id on "record_source" (email_id);
